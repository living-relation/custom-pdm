RES = []
ST_RAW = "https://raw.githubusercontent.com/STMicroelectronics/STM32_open_pin_data/master/mcu/"
ST_FILES = {"pins": "STM32F446R(C-E)Tx.xml", "gpio": "IP/GPIO-STM32F446_gpio_v1_0_Modes.xml"}
NS = {"s": "http://dummy.com"}
BOARDS = {"a": "hardware/board-a/DingoPDM.kicad_pcb", "b": "hardware/board-b-max/dingoPDM-Max.kicad_pcb"}
TC_PINS = {"PA4", "PA5"}             # DS DocID027107 Table 10 I/O structure TC (not 5 V tolerant); every other is FT
JTAG_PULLUP = {"PA15": "JTDI pull-up", "PB4": "NJTRST pull-up", "PA13": "SWDIO pull-up", "PA14": "SWCLK pull-down"}


def add(group, check, value, limit, verdict, note=""):
    RES.append(dict(group=group, check=check, value=value, limit=limit, verdict=verdict, note=note))


def st_xml(cache):
    os.makedirs(cache, exist_ok=True)
    out = {}
    for k, f in ST_FILES.items():
        p = os.path.join(cache, os.path.basename(f))
        if not os.path.exists(p):
            urllib.request.urlretrieve(ST_RAW + urllib.request.quote(f), p)
        out[k] = ET.parse(p).getroot()
    pos, sig = {}, {}
    for pin in out["pins"].findall("s:Pin", NS):
        name = re.split(r"[-\s]", pin.get("Name"))[0]
        pos[name] = pin.get("Position")
        sig[name] = [s.get("Name") for s in pin.findall("s:Signal", NS)]
    af = {}
    for gp in out["gpio"].findall("s:GPIO_Pin", NS):
        for ps in gp.findall("s:PinSignal", NS):
            v = ps.find("s:SpecificParameter/s:PossibleValue", NS)
            if v is not None and v.text and v.text.startswith("GPIO_AF"):
                af[(gp.get("Name"), ps.get("Name"))] = int(re.match(r"GPIO_AF(\d+)", v.text).group(1))
    return pos, sig, af


# ------------------------------------------------------------------ tiny C macro evaluator for board.h
def macros(text):
    obj, fn = {}, {}
    for m in re.finditer(r"^#define\s+(\w+)(\(([^)]*)\))?\s+(.*?)\s*$", re.sub(r"\\\n", " ", text), re.M):
        name, args, body = m.group(1), m.group(3), m.group(4)
        if m.group(2):
            fn[name] = ([a.strip() for a in args.split(",")], body)
        else:
            obj[name] = body
    return obj, fn


def expand(expr, obj, fn, depth=0):
    if depth > 30:
        raise RecursionError(expr)
    out, i = "", 0
    for m in re.finditer(r"\b[A-Za-z_]\w*\b", expr):
        out += expr[i:m.start()]
        w = m.group(0)
        i = m.end()
        if w in fn and i < len(expr) and expr[i] == "(":
            lvl, j = 0, i
            while True:
                lvl += {"(": 1, ")": -1}.get(expr[j], 0)
                if lvl == 0:
                    break
                j += 1
            inner, args, cur, lvl2 = expr[i + 1:j], [], "", 0
            for ch in inner:
                if ch == "," and lvl2 == 0:
                    args.append(cur)
                    cur = ""
                    continue
                lvl2 += {"(": 1, ")": -1}.get(ch, 0)
                cur += ch
            args.append(cur)
            params, body = fn[w]
            for p_, a_ in zip(params, args):
                body = re.sub(rf"\b{p_}\b", f"({a_})", body)
            out += "(" + expand(body, obj, fn, depth + 1) + ")"
            i = j + 1
            # resume the regex scan after the call
            return out + expand(expr[i:], obj, fn, depth)
        elif w in obj:
            out += "(" + expand(obj[w], obj, fn, depth + 1) + ")"
        else:
            out += w
    return out + expr[i:]


def cval(expr, obj, fn):
    e = expand(expr, obj, fn)
    e = re.sub(r"(\d+)U\b", r"\1", e).replace("/", "//")
    return eval(e, {"__builtins__": {}})


# ------------------------------------------------------------------ pins
def role_ok(line, net):
    n = net.upper().replace("/MCU/", "")
    m = re.match(r"LINE_PF(\d+)(?:_(\d+))?_(IN|IS|DEN|DSEL)$", line)
    if m:
        a, b, kind = m.groups()
        if kind == "IN":
            return n == f"PF_IN{a}"
        cands = {f"PF_{kind}{a}_{b}", f"PF_{kind}{a}"} if b else {f"PF_{kind}{a}"}
        return n in cands
    m = re.match(r"LINE_DI(\d+)$", line)
    if m:
        return n in (f"IN_{m.group(1)}", f"B_IN{m.group(1)}")
    fixed = {"LINE_BATT_SENSE": "BATT_SENSE", "LINE_USB_VBUS": "USB_VBUS", "LINE_CAN_STANDBY": "CAN_STANDBY",
             "LINE_I2C1_SCL": "I2C1_SCL", "LINE_I2C1_SDA": "I2C1_SDA", "LINE_CAN_RX": "CAN_RX", "LINE_CAN_TX": "CAN_TX",
             "LINE_USB_DM": "USB_D-", "LINE_USB_DP": "USB_D+", "LINE_SWDIO": "SWDIO", "LINE_SWCLK": "SWCLK", "LINE_SWO": "SWO"}
    if line in fixed:
        return n == fixed[line]
    if line == "LINE_AIN1":
        return n in ("PF_IS2", "B_AN")       # board A reuses the stock IS2 net name for the input-board AIN (J6.9)
    if line.startswith("LINE_LED"):
        return n.startswith("NET-(U4-")       # LED through its resistor
    if line == "LINE_UNUSED":
        return n.startswith("UNCONNECTED") or n == "BOOT1"
    return False


ALT = {"LINE_CAN_RX": "CAN1_RX", "LINE_CAN_TX": "CAN1_TX", "LINE_I2C1_SCL": "I2C1_SCL", "LINE_I2C1_SDA": "I2C1_SDA",
       "LINE_USB_DM": "USB_OTG_FS_DM", "LINE_USB_DP": "USB_OTG_FS_DP", "LINE_SWDIO": "SYS_JTMS-SWDIO",
       "LINE_SWCLK": "SYS_JTCK-SWCLK"}


def pin_audit(cache):
    import pcbnew
    pos, sig, af = st_xml(cache)
    for brd, path in BOARDS.items():
        b = pcbnew.LoadBoard(os.path.join(P.ROOT, path))
        u4 = [fp for fp in b.GetFootprints() if fp.GetReference() == "U4"][0]
        pad = {p.GetNumber(): p.GetNetname() for p in u4.Pads()}
        bynet = {}
        for fp in b.GetFootprints():
            for p in fp.Pads():
                bynet.setdefault(p.GetNetname(), []).append((fp.GetReference(), fp.GetValue()))
        bdir = os.path.join(P.ROOT, "firmware", "boards", f"custompdm_{brd}")
        bh = open(os.path.join(bdir, "board.h"), encoding="utf-8").read()
        obj, fn = macros(bh)
        lines = re.findall(r"#define (LINE_\w+)\s+PAL_LINE\(GPIO(\w), (\d+)U\)", bh)
        bad, used = [], {}
        for line, port, padn in lines:
            pin = f"P{port}{padn}"
            net = pad.get(pos.get(pin), "?")
            used[pin] = (line, net)
            if not role_ok(line, net):
                bad.append(f"{line} {pin} -> {net}")
        add("Pins", f"board {brd.upper()}: every firmware pin (board.h LINE_*) lands on the PCB net of its role",
            f"{len(lines) - len(bad)} of {len(lines)}", "all", "PASS" if not bad else "FAIL", "; ".join(bad))
        # alternate functions at boot (board.h) vs ST's AF table
        badaf = []
        for line, want in ALT.items():
            hit = [x for x in lines if x[0] == line]
            if not hit:
                continue
            _, port, padn = hit[0]
            n = int(padn)
            moder = cval(f"VAL_GPIO{port}_MODER", obj, fn)
            afr = cval(f"VAL_GPIO{port}_AFR{'L' if n < 8 else 'H'}", obj, fn)
            mode = (moder >> (2 * n)) & 3
            afn = (afr >> (4 * (n % 8))) & 15
            st = af.get((f"P{port}{n}", want))
            if mode != 2 or st is None or afn != st:
                badaf.append(f"{line}: mode {mode} AF{afn}, ST {want} = AF{st}")
        add("Pins", f"board {brd.upper()}: CAN1, I2C1, USB OTG FS, SWD in alternate mode with ST's AF number",
            f"{len(ALT) - len(badaf)} of {len(ALT)}", "all", "PASS" if not badaf else "FAIL", "; ".join(badaf) or
            "CAN1 AF9 (PB8 / PB9), I2C1 AF4 (PB6 / PB7), OTG_FS AF10 (PA11 / PA12), SWD AF0 (PA13 / PA14)")
        # ADC slots
        pc = open(os.path.join(bdir, "port.cpp"), encoding="utf-8").read()
        seq = {}
        for reg, base in (("sqr3", 1), ("sqr2", 7), ("sqr1", 13)):
            for m in re.finditer(r"SQ(\d+)_N\(ADC_CHANNEL_(\w+)\)", pc[pc.index(f".{reg}"):pc.index(f".{reg}") + 600]):
                seq.setdefault(int(m.group(1)), m.group(2))
        enum = re.search(r"enum class AnalogChannel\s*\{([^}]*)\}", open(os.path.join(bdir, "port.h"), encoding="utf-8").read()).group(1)
        enum = re.sub(r"//[^\n]*", "", enum)
        names = [re.sub(r"\s*=.*", "", x).strip() for x in enum.split(",")]
        names = [x for x in names if x]
        badadc = []
        for i, nm in enumerate(names):
            ch = seq.get(i + 1, "?")
            if ch in ("SENSOR", "VREFINT"):
                if nm not in ("TempSensor", "VRefInt"):
                    badadc.append(f"slot {i} {nm} = {ch}")
                continue
            pins = [p for p, s in sig.items() if f"ADC1_{ch}" in s]
            net = pad.get(pos.get(pins[0]), "?") if pins else "?"
            want = {"BattVolt": "BATT_SENSE", "AnIn1": ("PF_IS2", "B_AN")}.get(nm)
            nn = net.upper().replace("/MCU/", "")
            ok = (nn in want if isinstance(want, tuple) else nn == want) if want else \
                nn in {f"PF_IS{nm[2:]}", f"PF_IS{nm[2:].split('_')[0]}"}     # IS1_2 sits on the stock net PF_IS1
            if not ok:
                badadc.append(f"slot {i} {nm} = ADC1_{ch} ({pins[0] if pins else '?'}) -> {net}")
        add("Pins", f"board {brd.upper()}: every ADC slot (port.cpp adc1_cfg, AnalogChannel order) reads its own net",
            f"{len(names) - len(badadc)} of {len(names)}", "all", "PASS" if not badadc else "FAIL", "; ".join(badadc))
        # I/O structure: off-board / analog signals on TC pins (3.6 V max) are fine only below VDD + 0.3 V
        tc = [f"{p} {used[p][0]} ({used[p][1]})" for p in TC_PINS if p in used]
        add("Pins", f"board {brd.upper()}: TC (non-5 V-tolerant) pins PA4 / PA5", "; ".join(tc) or "unused",
            "only on-board signals that stay <= VDD (PROFET logic, IS behind the TLV9004)", "PASS",
            "every off-board input (input board) is on an FT pin; the inputs' BAT54S clamps hold them at <= 3.6 V")
        # boot pins
        boot0 = [r for r, v in bynet.get(pad.get("60"), []) if r != "U4"]
        pb2 = used.get("PB2", ("-", pad.get("28")))
        add("Pins", f"board {brd.upper()}: BOOT0 / BOOT1 (PB2)", f"BOOT0 net {pad.get('60')} ({', '.join(boot0)}); "
            f"PB2 = {pb2[0]} on {pb2[1]}", "BOOT0 pulled low (flash boot); BOOT1 low when BOOT0 is high (DFU)", "PASS",
            "board A: PB2 drives PROFET DEN through 4.7k (the DEN input has an internal pull-down: BOOT1 reads 0); "
            "board B: PB2 on its own 10k (R81)")
        # JTAG reset pull-ups on pins that drive a PROFET IN / DEN
        risky = [f"{p} ({JTAG_PULLUP[p]}) -> {used[p][0]}" for p in JTAG_PULLUP if p in used and re.match(r"LINE_PF\d+(_\d+)?_(IN|DEN)", used[p][0])]
        add("Pins", f"board {brd.upper()}: JTAG pins with a reset pull-up that drive a PROFET", "; ".join(risky) or "none",
            "none, or a glitch shorter than tON(DELAY)", "WARN" if risky else "PASS",
            "between reset release and the GPIO set-up in __early_init (a few us at 16 MHz HSI) the 40 kOhm JTAG "
            "pull-up and the 4.7k / PROFET IN pull-down decide; the output cannot turn on within tON(DELAY) >= 10 us; "
            "bench: scope that output at power-up" if risky else "")
        # NRST
        caps = [r for r, v in bynet.get(pad.get("7"), []) if r.startswith("C")]
        add("Pins", f"board {brd.upper()}: NRST", f"net {pad.get('7')}: {', '.join(r for r, v in bynet.get(pad.get('7'), []))}",
            "100 nF to GND (ST AN4488 3.3 'NRST', recommended)", "PASS" if caps else "WARN",
            "" if caps else "no capacitor: the internal 40k pull-up + filter only; a noisy car ground can reset the MCU "
            "(stock dingoPDM / Max the same). Hardware add (footprint): report to the coordinator")


# ------------------------------------------------------------------ clocks and CAN timing
def clocks_can():
    mc = open(os.path.join(P.ROOT, "firmware", "boards", "custompdm_a", "cfg", "mcuconf.h"), encoding="utf-8").read()
    g = lambda k: int(re.search(rf"STM32_{k}\s+(\d+)", mc).group(1))  # noqa: E731
    m_, n_, p_, q_ = g("PLLM_VALUE"), g("PLLN_VALUE"), g("PLLP_VALUE"), g("PLLQ_VALUE")
    vin = 8e6 / m_
    vco = vin * n_
    sys_ = vco / p_
    usb = vco / q_
    apb1 = sys_ / int(re.search(r"STM32_PPRE1\s+STM32_PPRE1_DIV(\d+)", mc).group(1))
    ok = 0.95e6 <= vin <= 2.1e6 and 100e6 <= vco <= 432e6 and sys_ <= 180e6 and abs(usb - 48e6) < 1 and apb1 <= 45e6
    add("Clocks", "HSE 8 MHz -> PLL", f"VCO in {vin / 1e6:.2f} MHz, VCO {vco / 1e6:.0f} MHz, SYSCLK {sys_ / 1e6:.0f} MHz, "
        f"USB {usb / 1e6:.2f} MHz, APB1 {apb1 / 1e6:.0f} MHz", "VCO in 0.95-2.1 MHz, VCO 100-432, SYSCLK <= 180, USB 48.00 "
        "(+-0.25 % for full speed), APB1 <= 45 MHz (DS Table 17, RM0390 6.3.2)", "PASS" if ok else "FAIL",
        "RM0390 recommends a 2 MHz VCO input to limit PLL jitter (1.6 MHz here: inside the range)")
    pc = open(os.path.join(P.ROOT, "firmware", "boards", "custompdm_a", "port.cpp"), encoding="utf-8").read()
    m = re.search(r"CAN_BTR_SJW\((\d+)\)\s*\|\s*CAN_BTR_BRP\((\d+)\)\s*\|\s*CAN_BTR_TS1\((\d+)\)\s*\|\s*CAN_BTR_TS2\((\d+)\)", pc)
    sjw, brp, ts1, ts2 = (int(x) + 1 for x in m.groups())
    tq = brp / apb1
    nbt = 1 + ts1 + ts2
    br = 1 / (tq * nbt)
    sp = (1 + ts1) / nbt
    # ISO 11898-1 / Bosch: prop segment needed = 2 x (transceiver loop + cable); the rest of TSEG1 is PS1
    # round trip: both transceivers' TXD -> RXD loop (120 ns max each, tx + rx) + 25 ns controller each + the cable twice
    t_loop = 2 * P.MCP2562FD["tprop"] + 2 * 25e-9
    best = None
    for length in (2, 5, 10, 20, 30, 40, 60):
        tprop = t_loop + 2 * 5e-9 * length
        prop_tq = int(-(-tprop // tq))
        ps1 = ts1 - prop_tq
        if ps1 < ts2:
            break
        best = length
    ps1 = ts1 - int(-(-(t_loop + 2 * 5e-9 * 5) // tq))
    df = min(sjw / (20 * nbt), min(ps1, ts2) / (2 * (13 * nbt - ts2)))
    crystal = 30e-6 + 30e-6 + 5e-6 * 10         # ABM3 code D2: tolerance + stability, 10 years ageing (ASSUMED)
    add("CAN timing", "1 Mbit/s bit timing (port.cpp canConfig1000)",
        f"{br / 1e3:.0f} kbit/s, {nbt} tq of {tq * 1e9:.1f} ns, sample point {sp * 100:.1f} %, SJW {sjw} tq",
        "1000 kbit/s exact; sample point 75-90 % (CiA 601-3); SJW >= 1", "PASS" if abs(br - 1e6) < 1 and 0.75 <= sp <= 0.9 else "FAIL",
        "CiA 601-3 suggests SJW = PS2 (2 tq here) for more resync margin; the Link ECU's own sample point should "
        "be within a few % (bench: read it from PCLink)")
    add("CAN timing", "oscillator tolerance at 1 Mbit/s (ISO 11898-1 conditions) vs the crystal",
        f"allowed +-{df * 1e6:.0f} ppm per node (5 m bus); crystal about +-{crystal * 1e6:.0f} ppm", "crystal << allowed",
        "PASS" if crystal * 2 < df else "FAIL", "the other nodes need the same; a 1 Mbit/s bus fits up to about "
        f"{best} m with this timing (MCP2562FD 120 ns, 5 ns/m)")


def watchdog_fram_sleep():
    mc = open(os.path.join(P.ROOT, "firmware", "boards", "custompdm_a", "cfg", "mcuconf.h"), encoding="utf-8").read()
    hc = open(os.path.join(P.ROOT, "firmware", "boards", "custompdm_a", "cfg", "halconf.h"), encoding="utf-8").read()
    iwdg = re.search(r"STM32_WDG_USE_IWDG\s+(\w+)", mc).group(1)
    hal = re.search(r"#define HAL_USE_WDG\s+(\w+)", hc).group(1)
    add("Watchdog", "independent watchdog (IWDG)", f"STM32_WDG_USE_IWDG {iwdg}, HAL_USE_WDG {hal}",
        "a hung firmware is reset", "WARN" if "TRUE" not in (iwdg, hal) else "PASS",
        "no watchdog (stock dingoFW the same): a firmware hang leaves every output as it was, with no current "
        "protection beyond the PROFETs' own. Adding one is a behaviour choice for Dan (a reset turns every output "
        "off for about 0.6 s until the boards boot): question for the coordinator")
    cfg = open(os.path.join(P.ROOT, "firmware", "core", "config_ext.cpp"), encoding="utf-8").read()
    writes = len(re.findall(r"fram\.Write\(", cfg))
    per_day = 50
    years = P.MB85RC64TA["endurance"] / (per_day * 365)
    add("FRAM", "MB85RC64TA write endurance vs the firmware's writes", f"{writes} write calls, only in WriteConfigExt (a "
        f"config save from the tool); at {per_day} saves a day the 1e13 cycles last {years:.1e} years",
        "> 20 years", "PASS", P.MB85RC64TA["src"] + "; reads (boot only) count too on FRAM: negligible")
    # sleep budget, per main board, from the battery (13 V), 25 C max / 85 C max data-sheet values
    v = 13.0
    items_33 = [("STM32F446 Stop, LP regulator, flash deep power-down", 0.9e-3, 6.0e-3),
                ("TLV9004 x 2 (8 amplifiers, no shutdown pin)", 8 * P.TLV9004["iq"], 8 * 85e-6),
                ("MCP2562FD standby (incl. VIO)", P.MCP2562FD["idd_stby"], P.MCP2562FD["idd_stby"]),
                ("MCP9808 shutdown", P.MCP9808["ishdn"], P.MCP9808["ishdn"]),
                ("MB85RC64TA standby (est.)", P.MB85RC64TA["istby"], P.MB85RC64TA["istby"]),
                ("TLV1117LV IQ", P.TLV1117LV["iq"], P.TLV1117LV["iq"])]
    i33_25 = sum(x[1] for x in items_33)
    i33_85 = sum(x[2] for x in items_33)
    eff = 0.5                                   # ASSUMED TSR efficiency at a few mW out
    tsr_nl = P.TSR["i_noload"]
    div = v / 51.7e3
    prof = {"A": 4 * P.PROFET["BTS7008-2EPA"]["ivs_off_85"], "B": 4 * P.PROFET["BTS70012-1ESP"]["ivs_off_85"] + 4 * P.PROFET["BTS7004-1EPP"]["ivs_off_85"]}
    tot = {}
    for brd in ("A", "B"):
        for t, i33 in (("25", i33_25), ("85", i33_85)):
            tot[(brd, t)] = tsr_nl + i33 * 3.3 / (v * eff) + div + prof[brd]
    pdm25 = 2 * tot[("A", "25")] + tot[("B", "25")]
    pdm85 = 2 * tot[("A", "85")] + tot[("B", "85")]
    days = 25.0 / pdm25 / 24                     # 50 Ah battery to 50 %
    add("Sleep current", "whole PDM asleep (3 boards), from the battery at 13 V (data-sheet max values)",
        f"{pdm25 * 1e3:.1f} mA at 25 C, {pdm85 * 1e3:.1f} mA at 85 C; per board A {tot[('A', '25')] * 1e3:.2f} mA: TSR no-load "
        f"{tsr_nl * 1e3:.1f} mA, battery divider {div * 1e3:.2f} mA, 3V3 parts {i33_25 * 1e3:.2f} mA at 3.3 V (amps "
        f"{8 * P.TLV9004['iq'] * 1e3:.2f} mA)", "<= 1 mA per module (usual OEM target); whole car budget about 20-50 mA",
        "WARN", f"a 50 Ah battery reaches 50 % in about {days:.0f} days at 25 C; biggest items: the TSR's own 1 mA "
        "no-load draw x 3, the 47k / 4.7k divider x 3 and the always-on op-amps; the input boards' pull-ups add "
        "0.33 mA per input held low. Bench: measure the PDM's sleep current")
    add("CPU load", "worst-case main-loop time with every feature on", "not measured: the host sim has no cycle model "
        "and ChibiOS idles without WFI (Renode instruction counts include the idle loop)", "DeviceThread loop = work + "
        "2 ms sleep, so overload stretches the period instead of missing a deadline", "INFO",
        "bench (or a Renode run with a function-entry hook on CyclicUpdate): measure the loop period with all features "
        "configured; s1 measured ECU -> output latency 3.7 ms in the host sim")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json")
    ap.add_argument("--cache", default=os.path.join(tempfile.gettempdir(), "presim-st"))
    a = ap.parse_args()
    pin_audit(a.cache)
    clocks_can()
    watchdog_fram_sleep()
    for r in RES:
        print(f"{r['verdict']:<5} [{r['group']}] {r['check']}: {r['value']} (limit {r['limit']})" + (f" - {r['note']}" if r['note'] else ""))
    cnt = {v: sum(r["verdict"] == v for r in RES) for v in ("PASS", "WARN", "FAIL", "INFO")}
    print("TOTAL", cnt)
    if a.json:
        json.dump(RES, open(a.json, "w"), indent=1)
    return 1 if cnt["FAIL"] else 0


if __name__ == "__main__":
    sys.exit(main())
