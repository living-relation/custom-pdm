"""Presim item 4: MCU / firmware - pin-function audit (firmware board.h vs the PCB nets vs ST's pin data), clock tree,
CAN bit timing at 1 Mbit/s, watchdog, FRAM endurance, sleep-current budget.

usage (repo root, KiCad 9 python with pcbnew): python tools/verify_mcu.py [--json out.json] [--cache DIR]
    downloads ST's STM32_open_pin_data (BSD-3, github.com/STMicroelectronics/STM32_open_pin_data) pin and GPIO-AF XML
    for the STM32F446R(C-E)Tx once into --cache (default %TEMP%/presim-st). Exit code 1 on any FAIL.

Pin audit, per board (custompdm_a = A1 / A2, custompdm_b = B): every firmware LINE_x (board.h, generated by
port_boards.py) -> port / pad -> LQFP64 position (ST XML) -> the MCU U4 pad's net on the PCB, checked against the
role the firmware gives it; alternate functions (board.h VAL_GPIOx_MODER / AFRL / AFRH evaluated here) against ST's
AF table; every ADC slot (port.cpp adc1_cfg) against the pin's ADC1_INx; I/O structure (DS Table 10: PA4 / PA5 are
TC, all other used pins FT); boot pins; JTAG pins with reset pull-ups that drive a PROFET; NRST.
"""
