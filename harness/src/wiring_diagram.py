def wrap(parts, size, maxw, sep=", "):
    out = []; cur = ""
    for p in parts:
        t = cur + sep + p if cur else p
        if cur and tw(t, size) > maxw: out.append(cur + sep.rstrip()); cur = p
        else: cur = t
    return out + [cur] if cur else out

