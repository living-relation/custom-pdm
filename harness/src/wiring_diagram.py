def tw(s, size, bold=False):
    t = _HB if bold else _HV
    assert all(32 <= ord(c) <= 126 for c in s), ("non-ASCII text in the drawing", s)
    return sum(t[ord(c) - 32] for c in s) * size / 1000.0

HEX = {"Red": "#d32f2f", "White": "#ffffff", "Violet": "#7b1fa2", "Black": "#1a1a1a", "Yellow": "#fdd835", "Green": "#2e7d32", "Gray": "#9e9e9e"}
