# Canvas: records primitives, writes SVG and PDF, keeps text boxes and line segments for the checks
# ------------------------------------------------------------------------------------------------------------------
class Canvas:
    def __init__(self, name):
        self.name = name; self.ops = []; self.texts = []; self.segs = []; self.rects = []; self.problems = []
    def line(self, pts, w=0.25, color=INK, dash=None, owner=None):
        self.ops.append(("line", [(round(x, 3), round(y, 3)) for x, y in pts], w, color, dash))
        if owner:
            for a, b in zip(pts[:-1], pts[1:]): self.segs.append((owner, a, b))
    def rect(self, x, y, w, h, fill=None, stroke=INK, sw=0.25, dash=None, owner=None):
        self.ops.append(("rect", round(x, 3), round(y, 3), round(w, 3), round(h, 3), fill, stroke, sw, dash))
        if owner: self.rects.append((owner, (x, y, x + w, y + h)))
    def text(self, x, y, s, size=2.2, bold=False, anchor="start", color=INK, rot=0, owner=None):
        """y = baseline; rot 90 = reads bottom to top (text runs up the page from x, y)"""
        s = str(s); w = tw(s, size, bold)
        if not s: return 0.0
        self.ops.append(("text", round(x, 3), round(y, 3), s, size, bold, anchor, color, rot))
        off = {"start": 0.0, "middle": -w / 2, "end": -w}[anchor]
        asc, desc = 0.74 * size, 0.2 * size
        box = (x + off, y - asc, x + off + w, y + desc) if not rot else (x - asc, y - off - w, x + desc, y - off)
        self.texts.append((owner, s, box))
        return w
    def begin(self, **attrs): self.ops.append(("begin", attrs))
    def end(self): self.ops.append(("end",))

    def svg(self, title):
        e = lambda s: s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
        o = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<!-- GENERATED by harness/src/enclosure_harness.py diagram from harness/enclosure-*.csv. Do not edit. -->',
             f'<svg xmlns="http://www.w3.org/2000/svg" width="17in" height="11in" viewBox="0 0 {PAGE_W} {PAGE_H}" font-family="Helvetica, Arial, sans-serif">',
             f'<title>{e(title)}</title>', f'<rect x="0" y="0" width="{PAGE_W}" height="{PAGE_H}" fill="#ffffff"/>']
        for op in self.ops:
            k = op[0]
            if k == "begin": o.append("<g " + " ".join(f'{a.rstrip("_").replace("_", "-")}="{e(str(v))}"' for a, v in op[1].items()) + ">")
            elif k == "end": o.append("</g>")
            elif k == "line":
                _, pts, w, color, dash = op
                d = f' stroke-dasharray="{dash}"' if dash else ""
                o.append(f'<polyline points="{" ".join(f"{x:g},{y:g}" for x, y in pts)}" fill="none" stroke="{color}" stroke-width="{w:g}"{d}/>')
            elif k == "rect":
                _, x, y, w, h, fill, stroke, sw, dash = op
                d = f' stroke-dasharray="{dash}"' if dash else ""
                st = f' stroke="{stroke}" stroke-width="{sw:g}"' if stroke else ""
                o.append(f'<rect x="{x:g}" y="{y:g}" width="{w:g}" height="{h:g}" fill="{fill or "none"}"{st}{d}/>')
            elif k == "text":
                _, x, y, s, size, bold, anchor, color, rot = op
                a = "" if anchor == "start" else f' text-anchor="{anchor}"'
                b = ' font-weight="bold"' if bold else ""
                f = "" if color == INK else f' fill="{color}"'
                r = f' transform="rotate(-90 {x:g} {y:g})"' if rot else ""
                o.append(f'<text x="{x:g}" y="{y:g}" font-size="{size:g}"{a}{b}{f}{r}>{e(s)}</text>')
        o.append("</svg>")
        return "\n".join(o) + "\n"

    def pdf_stream(self):
        def rgb(c): return " ".join(f"{int(c[i:i + 2], 16) / 255:.3f}".rstrip("0").rstrip(".") for i in (1, 3, 5))
        P = lambda x, y: f"{x * K:.2f} {(PAGE_H - y) * K:.2f}"
        o = []
        for op in self.ops:
            k = op[0]
            if k == "line":
                _, pts, w, color, dash = op
                dd = "[" + " ".join(f"{float(v) * K:.2f}" for v in dash.split()) + "] 0 d" if dash else "[] 0 d"
                o.append(f"{rgb(color)} RG {w * K:.2f} w {dd} {P(*pts[0])} m " + " ".join(P(*p) + " l" for p in pts[1:]) + " S")
            elif k == "rect":
                _, x, y, w, h, fill, stroke, sw, dash = op
                dd = "[" + " ".join(f"{float(v) * K:.2f}" for v in dash.split()) + "] 0 d" if dash else "[] 0 d"
                paint = "B" if fill and stroke else "f" if fill else "S"
                o.append((f"{rgb(fill)} rg " if fill else "") + (f"{rgb(stroke)} RG {sw * K:.2f} w {dd} " if stroke else "")
                         + f"{x * K:.2f} {(PAGE_H - y - h) * K:.2f} {w * K:.2f} {h * K:.2f} re {paint}")
            elif k == "text":
                _, x, y, s, size, bold, anchor, color, rot = op
                w = tw(s, size, bold); off = {"start": 0.0, "middle": -w / 2, "end": -w}[anchor]
                esc = s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
                tm = f"1 0 0 1 {P(x + off, y)}" if not rot else f"0 1 -1 0 {P(x, y - off)}"
                o.append(f"BT {rgb(color)} rg /F{2 if bold else 1} {size * K:.2f} Tf {tm} Tm ({esc}) Tj ET")
        return "\n".join(o) + "\n"

def write_pdf(sheets, title, keywords):
    """Minimal multi-page PDF 1.4 (vector, base-14 Helvetica, no compression, no timestamps: same input -> same bytes)"""
    objs = []
    def add(body): objs.append(body); return len(objs)
    esc = lambda s: s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
    cat = add(None); pages = add(None)
    f1 = add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>")
    f2 = add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>")
    kids = []
    for c in sheets:
        st = c.pdf_stream()
        cs = add(f"<< /Length {len(st.encode('latin-1'))} >>\nstream\n{st}endstream")
        kids.append(add(f"<< /Type /Page /Parent {pages} 0 R /MediaBox [0 0 {PAGE_W * K:.2f} {PAGE_H * K:.2f}] /Contents {cs} 0 R "
                        f"/Resources << /Font << /F1 {f1} 0 R /F2 {f2} 0 R >> >> >>"))
    objs[cat - 1] = f"<< /Type /Catalog /Pages {pages} 0 R >>"
    objs[pages - 1] = f"<< /Type /Pages /Count {len(kids)} /Kids [{' '.join(f'{k} 0 R' for k in kids)}] >>"
    info = add(f"<< /Title ({esc(title)}) /Creator (harness/src/enclosure_harness.py diagram) /Keywords ({esc(keywords)}) >>")
    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n"); offs = []
    for i, body in enumerate(objs, 1):
        offs.append(len(out)); out += f"{i} 0 obj\n{body}\nendobj\n".encode("latin-1")
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode() + b"".join(f"{o:010d} 00000 n \n".encode() for o in offs)
    out += f"trailer\n<< /Size {len(objs) + 1} /Root {cat} 0 R /Info {info} 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return bytes(out)

