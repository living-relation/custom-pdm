PIN_PREFIX = {"HUB-P1": "PORT1:", "HUB-P2": "PORT2:", "HUB-P3": "PORT3:", "U1-B": "USB-C in:"}

def block_of(c): return MERGE.get(c, c)
def pin_name(conn, c, p):
    k = conn[c]["kind"]
    return c.split("-")[-1] if k == "ring" else c if k == "splice" else p

def runs(pairs):
    """[(a, b), ...] in wire order -> two strings with the same grouping: '1-5 9 10' and '9-13 14 35'"""
    out = []; i = 0; num = lambda v: v.isdigit()
    while i < len(pairs):
        j = i
        while (j + 1 < len(pairs) and all(num(pairs[j][k]) and num(pairs[j + 1][k]) and int(pairs[j + 1][k]) == int(pairs[j][k]) + 1 for k in (0, 1))): j += 1
        if j - i >= 2: out.append((f"{pairs[i][0]}-{pairs[j][0]}", f"{pairs[i][1]}-{pairs[j][1]}")); i = j + 1
        else: out.append(pairs[i]); i += 1
    return " ".join(a for a, _ in out), " ".join(b for _, b in out)

def squeeze(names):
    """['A1_IN3_MCU', 'A1_IN4_MCU', ..., 'GND_A1', 'GND_A1'] -> ['A1_IN3-7_MCU', 'GND_A1 x2'] (wire order kept)"""
    out = []; i = 0
    def split(n):
        m = re.match(r"^(.*?)(\d+)(\D*)$", n)
        return (m.group(1), int(m.group(2)), m.group(3)) if m else None
    while i < len(names):
        j = i
        while j + 1 < len(names) and names[j + 1] == names[i]: j += 1
        if j > i: out.append(f"{names[i]} x{j - i + 1}"); i = j + 1; continue
        a = split(names[i])
        while a and j + 1 < len(names) and split(names[j + 1]) == (a[0], a[1] + (j + 1 - i), a[2]): j += 1
        out.append(f"{a[0]}{a[1]}-{a[1] + j - i}{a[2]}" if j > i else names[i]); i = j + 1
    return out

def id_runs(ids):
    out = []; i = 0; n = lambda s: int(s[1:])
    while i < len(ids):
        j = i
        while j + 1 < len(ids) and n(ids[j + 1]) == n(ids[j]) + 1: j += 1
        out.append(ids[i] if j == i else f"{ids[i]}-{ids[j]}" if j > i + 1 else f"{ids[i]} {ids[j]}"); i = j + 1
    return " ".join(out)

def make_lines(rows, conn):
    lines = {}
    for r in rows:
        a, b = block_of(r["From connector"]), block_of(r["To connector"])
        key = (a, b) if (a, b) in lines or (b, a) not in lines else (b, a)
        L = lines.setdefault(key, dict(a=key[0], b=key[1], wires=[]))
        ends = {a: (r["From connector"], r["From pin"]), b: (r["To connector"], r["To pin"])}
        L["wires"].append(dict(row=r, a=ends[key[0]], b=ends[key[1]]))
    for i, L in enumerate(lines.values(), 1):
        L["id"] = f"L{i:02d}"; ws = L["wires"]
        pa, pb = runs([(pin_name(conn, *w["a"]), pin_name(conn, *w["b"])) for w in ws])
        pre = lambda side: " ".join(sorted({PIN_PREFIX.get(w[side][0], "") for w in ws})).strip()
        L["pins_a"], L["pins_b"] = (pre("a") + " " + pa).strip(), (pre("b") + " " + pb).strip()
        L["signals"] = squeeze([w["row"]["Signal"] for w in ws])
        L["ids"] = id_runs([w["row"]["Wire ID"] for w in ws])
        awg = sorted({w["row"]["AWG"] for w in ws}); cols = []
        for w in ws:
            if w["row"]["Color"] not in cols: cols.append(w["row"]["Color"])
        cnt = {c: sum(1 for w in ws if w["row"]["Color"] == c) for c in cols}
        L["colors"] = cols
        ctxt = cols[0] if len(cols) == 1 else " ".join(f"{cnt[c]} {c}" for c in cols) if max(cnt.values()) > 1 else " ".join(cols)
        grp = sorted({w["row"]["Twist/Shield group"] for w in ws} - {""})
        kind = (", " + grp[0]) if grp and grp[0].startswith("TP") else (", cable " + grp[0]) if grp else ""
        gauge = "AWG TBD" if awg == ["TBD"] else "/".join(awg) + " AWG"
        L["spec"] = f"{len(ws)} x {gauge} {ctxt}{kind}"
        L["awg"] = min((int(a) for a in awg if a.isdigit()), default=30)
    return list(lines.values())

